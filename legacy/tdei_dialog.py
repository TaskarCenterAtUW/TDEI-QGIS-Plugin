    def _plugin_version(self):
        metadata = os.path.join(os.path.dirname(__file__), 'metadata.txt')
        try:
            with open(metadata) as handle:
                for line in handle:
                    if line.startswith('version='):
                        return line.split('=', 1)[1].strip()
        except OSError:
            pass
        return '0.1'

