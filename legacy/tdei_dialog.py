    def show_login(self):
        self.stackedWidget.setCurrentWidget(self.pageLogin)
        self._set_login_status('')
        self.btnLogin.setEnabled(True)
        self.resize(720, 720)

    def sign_in(self):
        username = self.txtUsername.text().strip()
        password = self.txtPassword.text()
        if not username or not password:
            self._set_login_status(
                'Enter both username and password.', error=True)
            return

        self.btnLogin.setEnabled(False)
        self._set_login_status('Signing in…')
        QApplication.setOverrideCursor(Qt.WaitCursor)
        QApplication.processEvents()
        try:
            self.access_token = authenticate(username, password)
        except TdeiApiError as exc:
            self.access_token = None
            self._set_login_status(str(exc), error=True)
            self.btnLogin.setEnabled(True)
            self.txtPassword.setFocus()
            self.txtPassword.selectAll()
            return
        finally:
            QApplication.restoreOverrideCursor()

        self._username = username
        self.txtPassword.clear()
        self.lblUser.setText('Signed in as {}'.format(self._username))
        self.resize(780, 520)
        self.stackedWidget.setCurrentWidget(self.pageDatasets)
        self.load_datasets()

    def load_datasets(self):
        if not self.access_token:
            self.show_login()
            self._set_login_status('Please sign in again.', error=True)
            return

        self.lblTableStatus.setText('Loading datasets…')
        self.btnRefresh.setEnabled(False)
        QApplication.setOverrideCursor(Qt.WaitCursor)
        QApplication.processEvents()
        try:
            rows = list_datasets(self.access_token)
        except TdeiApiError as exc:
            if exc.status_code == 401:
                self.sign_out()
                self._set_login_status(
                    'Session expired. Please sign in again.', error=True)
                return
            self.lblTableStatus.setText(str(exc))
            return
        finally:
            QApplication.restoreOverrideCursor()
            self.btnRefresh.setEnabled(True)

        self._fill_table(rows)
        count = len(rows)
        if count == 1:
            self.lblTableStatus.setText('1 dataset')
        else:
            self.lblTableStatus.setText('{} datasets'.format(count))

    def view_in_qgis(self, dataset_id):
        if not dataset_id:
            self.lblTableStatus.setText('Missing tdei_dataset_id.')
            return
        if not self.access_token:
            self.show_login()
            self._set_login_status('Please sign in again.', error=True)
            return
        if is_dataset_loaded(dataset_id):
            zoom_to_dataset(dataset_id, self.iface)
            self.lblTableStatus.setText(
                'Dataset {} is already loaded.'.format(dataset_id))
            return
        if self._loading_dataset_id:
            self.lblTableStatus.setText('Another dataset is still loading.')
            return

        self._loading_dataset_id = dataset_id
        self.lblTableStatus.setText(
            'Downloading {}…'.format(dataset_id))
        QApplication.setOverrideCursor(Qt.WaitCursor)
        QApplication.processEvents()
        try:
            cache_dir = cache_dir_for(dataset_id)
            zip_path = os.path.join(cache_dir, 'package.zip')
            download_osw_zip(self.access_token, dataset_id, zip_path)
            self.lblTableStatus.setText('Extracting {}…'.format(dataset_id))
            QApplication.processEvents()
            geojsons = unpack_osw_package(
                zip_path, os.path.join(cache_dir, 'extracted'))
            self.lblTableStatus.setText(
                'Loading {} into QGIS…'.format(dataset_id))
            QApplication.processEvents()
            layers = load_geojsons_into_group(
                dataset_id, geojsons, iface=self.iface)
        except TdeiApiError as exc:
            if exc.status_code == 401:
                self.sign_out()
                self._set_login_status(
                    'Session expired. Please sign in again.', error=True)
                return
            self.lblTableStatus.setText(str(exc))
            return
        except Exception as exc:
            self.lblTableStatus.setText(
                'Could not load dataset: {}'.format(exc))
            return
        finally:
            self._loading_dataset_id = None
            QApplication.restoreOverrideCursor()

        self.lblTableStatus.setText(
            'Loaded {} layer(s) in group {}.'.format(
                len(layers), dataset_id))

    def sign_out(self):
        self.access_token = None
        self._username = ''
        self.tblDatasets.setRowCount(0)
        self.lblTableStatus.setText('')
        self.lblUser.setText('')
        self.show_login()

    def _fill_table(self, rows):
        self.tblDatasets.setRowCount(0)
        self.tblDatasets.setRowCount(len(rows))
        for row_index, (dataset_id, name) in enumerate(rows):
            id_item = QTableWidgetItem(dataset_id)
            name_item = QTableWidgetItem(name)
            self.tblDatasets.setItem(row_index, 0, id_item)
            self.tblDatasets.setItem(row_index, 1, name_item)
            view_button = QPushButton('View in QGIS')
            view_button.clicked.connect(
                lambda _checked=False, did=dataset_id: self.view_in_qgis(did))
            self.tblDatasets.setCellWidget(row_index, 2, view_button)
