class _LoginBackgroundFilter(QObject):
    """Paint the TDEI portal login background so it covers the panel."""

    def __init__(self, pixmap, parent=None):
        super(_LoginBackgroundFilter, self).__init__(parent)
        self._pixmap = pixmap

    def eventFilter(self, obj, event):
        if event.type() == QEvent.Paint:
            painter = QPainter(obj)
            painter.setRenderHint(QPainter.SmoothPixmapTransform)
            scaled = self._pixmap.scaled(
                obj.size(),
                Qt.KeepAspectRatioByExpanding,
                Qt.SmoothTransformation)
            x = (obj.width() - scaled.width()) // 2
            y = (obj.height() - scaled.height()) // 2
            painter.drawPixmap(x, y, scaled)
            return True
        return False


